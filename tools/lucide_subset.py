#!/usr/bin/env python3
"""Cuts the Lucide icon font down to the icons the launcher draws.

Usage: python3 tools/lucide_subset.py <lucide-static package folder>
  (the npm package "lucide-static": `npm pack lucide-static@<version>`, then untar it; needs fontTools)

Writes resources/fonts/Lucide.ttf (the subset, embedded by cmake/embed_fonts.cmake) and
src/launcher/ui/components/lucide.h (each icon's code point). To add an icon: add its Lucide name below, run this
again, then map it in ui::DrawIcon (components/core.cpp). docs/launcher_ui.md, "Icons".
"""
import json
import pathlib
import sys

from fontTools import subset

# The Lucide names, in the order of ui::Icon (components/core.h).
ICONS = [
    "check", "x", "plus", "minus", "chevron-down", "chevron-up", "chevron-left", "chevron-right", "arrow-up", "arrow-down",
    "search", "settings", "info", "triangle-alert", "circle-x", "download", "trash-2", "folder", "disc-3", "play", "timer",
    "ellipsis", "star", "circle-check", "circle-arrow-down", "circle-pause", "circle-dashed", "loader-circle", "gamepad-2",
]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    package = pathlib.Path(sys.argv[1])
    root = pathlib.Path(__file__).resolve().parent.parent
    version = json.loads((package / "package.json").read_text())["version"]
    codepoints = json.loads((package / "font" / "codepoints.json").read_text())

    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ["*"]  # keeps the copyright and licence names
    options.notdef_outline = True
    font = subset.load_font(str(package / "font" / "lucide.ttf"), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[codepoints[name] for name in ICONS])
    subsetter.subset(font)
    subset.save_font(font, str(root / "resources" / "fonts" / "Lucide.ttf"), options)

    lines = [
        f"// Generated by tools/lucide_subset.py from lucide-static {version} (ISC licence). Do not edit.",
        "// Each icon's code point in resources/fonts/Lucide.ttf.",
        "#pragma once",
        "",
        "namespace ui::lucide",
        "{",
    ]
    for name in ICONS:
        identifier = "".join(part.capitalize() for part in name.split("-"))
        lines.append(f"    constexpr unsigned {identifier} = 0x{codepoints[name]:X}; // {name}")
    lines += ["}", ""]
    (root / "src" / "launcher" / "ui" / "components" / "lucide.h").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
